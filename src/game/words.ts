export const ALL_WORDS: readonly WordEntry[] = CATEGORIES.flatMap(({ id }) =>
  BANK[id].map(([word, hint]) => ({ word, hint, category: id })),
)

export function getCategory(id: CategoryId): Category {
  return CATEGORIES.find((c) => c.id === id) ?? CATEGORIES[0]
}

export function wordsIn(category: CategoryId | 'any'): readonly WordEntry[] {
  return category === 'any' ? ALL_WORDS : ALL_WORDS.filter((w) => w.category === category)
}
